/**
 * Pedagogical uppercase stroke guides in a 0–100 unit box.
 * Each letter is ordered polylines (writing order) used as hollow traces + scoring waypoints.
 */
export type Point = {x: number; y: number};
export type LetterStrokes = Point[][];

/** Densify a polyline so scoring has even coverage along the stroke. */
export function densifyStroke(points: Point[], step = 6): Point[] {
  if (points.length < 2) {
    return points.slice();
  }
  const out: Point[] = [];
  for (let i = 0; i < points.length - 1; i++) {
    const a = points[i];
    const b = points[i + 1];
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    const dist = Math.hypot(dx, dy);
    const n = Math.max(1, Math.ceil(dist / step));
    for (let k = 0; k < n; k++) {
      const t = k / n;
      out.push({x: a.x + dx * t, y: a.y + dy * t});
    }
  }
  out.push(points[points.length - 1]);
  return out;
}

export function densifyLetter(strokes: LetterStrokes, step = 6): Point[] {
  return strokes.flatMap(s => densifyStroke(s, step));
}

