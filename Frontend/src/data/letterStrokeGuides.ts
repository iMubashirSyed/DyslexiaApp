export function getLetterStrokes(ch: string): LetterStrokes | null {
  if (LOWERCASE_STROKES[ch]) {
    return LOWERCASE_STROKES[ch];
  }
  if (LETTER_STROKES[ch]) {
    return LETTER_STROKES[ch];
  }
  const lower = ch.toLowerCase();
  if (LOWERCASE_STROKES[lower]) {
    return LOWERCASE_STROKES[lower];
  }
  return LETTER_STROKES[ch.toUpperCase()] ?? null;
}

export function hasTraceableLetters(word: string): boolean {
  return /^[A-Za-z]+$/.test(word) && [...word].every(c => getLetterStrokes(c));
}
